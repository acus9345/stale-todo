import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { after, before, describe, it } from "node:test";
import { COMMENT_MARKER, ISSUE_MARKER } from "../dist/github.js";
import { run } from "../dist/main.js";
import { scanReport } from "../dist/scan.js";

const TAGS = ["TODO", "FIXME", "HACK", "XXX"];
const NOW = Date.parse("2026-10-20T12:00:00Z");

describe("ignore comments and vendored files", () => {
  let repo: string;
  const write = (path: string, text: string) => {
    mkdirSync(dirname(join(repo, path)), { recursive: true });
    writeFileSync(join(repo, path), text);
  };

  before(() => {
    repo = mkdtempSync(join(tmpdir(), "stale-todo-ignore-"));
    const git = (args: string[]) => execFileSync("git", args, { cwd: repo, encoding: "utf8" });
    git(["init", "-q", "-b", "main"]);
    write("src/a.ts", "// TODO: keep\n// TODO: skip me stale-todo-ignore\n// stale-todo-ignore-next-line\n// FIXME: skipped too\n// HACK: kept\n");
    write("src/b.ts", "// stale-todo-ignore-file\n// TODO: one\n// TODO: two\n");
    write("vendor/lib.js", "// TODO: vendored\n");
    write("third_party/x/y.c", "// TODO: vendored\n");
    write("web/app.min.js", "/* TODO */\n");
    write("gen/api.ts", "// Code generated by protoc. DO NOT EDIT.\n// TODO: generated\n");
    write("gen/schema.ts", "/** @generated */\n// TODO: generated\n");
    write("lib/marked.ts", "// TODO: marked generated\n");
    write("vendor/ours/keep.ts", "// TODO: ours\n");
    write(".gitattributes", "lib/marked.ts linguist-generated\nvendor/ours/** -linguist-vendored\n");
    git(["add", "-A"]);
    git(["-c", "user.name=Ada", "-c", "user.email=ada@example.com", "commit", "-q", "-m", "init"]);
  });
  after(() => rmSync(repo, { recursive: true, force: true }));

  it("skips lines and files marked stale-todo-ignore", async () => {
    const { todos, ignored } = await scanReport({ cwd: repo, tags: TAGS, include: ["src/**"] });
    assert.deepEqual(
      todos.map((t) => `${t.file}:${t.line}`),
      ["src/a.ts:1", "src/a.ts:5"],
    );
    assert.equal(ignored, 4);
  });

  it("skips vendored and generated files, unless .gitattributes says otherwise", async () => {
    const { todos, skippedFiles } = await scanReport({ cwd: repo, tags: TAGS, exclude: ["src/**"] });
    assert.deepEqual(
      todos.map((t) => t.file),
      ["vendor/ours/keep.ts"],
    );
    assert.deepEqual(skippedFiles, ["gen/api.ts", "gen/schema.ts", "lib/marked.ts", "third_party/x/y.c", "vendor/lib.js", "web/app.min.js"]);
    const all = await scanReport({ cwd: repo, tags: TAGS, exclude: ["src/**"], skipVendored: false });
    assert.equal(all.todos.length, 7);
    assert.deepEqual(all.skippedFiles, []);
  });

  it("reports ignored and skipped counts", async () => {
    const outFile = join(repo, "..", `out-ignore-${Date.now()}.txt`);
    writeFileSync(outFile, "");
    const logs: string[] = [];
    await run({ GITHUB_WORKSPACE: repo, GITHUB_OUTPUT: outFile, INPUT_DAYS: "0" }, { log: (l) => logs.push(l) });
    assert.match(logs.at(-1)!, /^Found 3 TODOs, 3 older than 0 days\. \(4 ignored by comment, 6 vendored or generated files skipped\)$/);
    assert.match(readFileSync(outFile, "utf8"), /^ignored<<ghadelimiter_[\w-]+\n4\n/m);
    rmSync(outFile);
  });
});

/** An in-memory stand-in for the parts of the GitHub API the action calls. */
function fakeGitHub(options: { status?: number } = {}) {
  const comments: { id: number; body: string; html_url: string }[] = [];
  const issues: { number: number; title: string; body: string; state: string; labels: string[]; html_url: string; pull_request?: object }[] = [
    { number: 1, title: "A pull request", body: ISSUE_MARKER, state: "open", labels: [], html_url: "u/1", pull_request: {} },
    { number: 2, title: "Unrelated", body: "hello", state: "open", labels: [], html_url: "u/2" },
  ];
  const requests: string[] = [];
  let nextId = 100;
  const fetch = (async (url: string, init: RequestInit = {}) => {
    const method = init.method ?? "GET";
    const { pathname, searchParams } = new URL(url);
    requests.push(`${method} ${pathname}`);
    assert.equal((init.headers as Record<string, string>).authorization, "Bearer t0ken");
    const json = (status: number, value: unknown) => new Response(JSON.stringify(value), { status });
    if (options.status) return json(options.status, { message: "Resource not accessible by integration" });
    const body = init.body ? JSON.parse(String(init.body)) : {};
    let m: RegExpExecArray | null;
    if ((m = /^\/repos\/acme\/app\/issues\/(\d+)\/comments$/.exec(pathname))) {
      if (method === "GET") return json(200, searchParams.get("page") === "1" ? comments : []);
      const c = { id: nextId++, body: body.body, html_url: `c/${nextId}` };
      comments.push(c);
      return json(201, c);
    }
    if ((m = /^\/repos\/acme\/app\/issues\/comments\/(\d+)$/.exec(pathname))) {
      const c = comments.find((x) => x.id === Number(m![1]))!;
      c.body = body.body;
      return json(200, c);
    }
    if (pathname === "/repos/acme/app/issues") {
      if (method === "GET") return json(200, issues.filter((i) => i.state === searchParams.get("state")));
      const i = { number: issues.length + 1, title: body.title, body: body.body, state: "open", labels: body.labels ?? [], html_url: `u/${issues.length + 1}` };
      issues.push(i);
      return json(201, i);
    }
    if ((m = /^\/repos\/acme\/app\/issues\/(\d+)$/.exec(pathname))) {
      const i = issues.find((x) => x.number === Number(m![1]))!;
      Object.assign(i, body);
      return json(200, i);
    }
    return json(404, { message: "Not Found" });
  }) as typeof globalThis.fetch;
  return { fetch, comments, issues, requests };
}

describe("comment and issue", () => {
  let repo: string;
  let event: string;
  const git = (args: string[], date?: string) =>
    execFileSync("git", args, {
      cwd: repo,
      encoding: "utf8",
      env: { ...process.env, ...(date ? { GIT_AUTHOR_DATE: date, GIT_COMMITTER_DATE: date } : {}) },
    });

  before(() => {
    repo = mkdtempSync(join(tmpdir(), "stale-todo-gh-"));
    git(["init", "-q", "-b", "main"]);
    writeFileSync(join(repo, "a.ts"), "// TODO: old one\n");
    git(["add", "-A"]);
    git(["-c", "user.name=Ada", "-c", "user.email=ada@example.com", "commit", "-q", "-m", "old"], "2024-01-15T10:00:00Z");
    event = join(repo, "..", `event-gh-${Date.now()}.json`);
    writeFileSync(event, JSON.stringify({ pull_request: { number: 7, base: { sha: "x" } } }));
  });
  after(() => {
    rmSync(repo, { recursive: true, force: true });
    rmSync(event, { force: true });
  });

  const baseEnv = () => ({
    GITHUB_WORKSPACE: repo,
    GITHUB_REPOSITORY: "acme/app",
    GITHUB_SHA: "abc",
    GITHUB_RUN_ID: "42",
    GITHUB_EVENT_PATH: event,
    INPUT_TOKEN: "t0ken",
  });

  it("keeps one comment on the pull request", async () => {
    const gh = fakeGitHub();
    const logs: string[] = [];
    const env = { ...baseEnv(), INPUT_COMMENT: "true", INPUT_DAYS: "90" };
    await run(env, { log: (l) => logs.push(l), now: NOW, fetch: gh.fetch });
    assert.equal(gh.comments.length, 1);
    assert.ok(gh.comments[0]!.body.startsWith(`${COMMENT_MARKER}\n## Stale TODOs`));
    assert.match(gh.comments[0]!.body, /\*\*1\*\* of \*\*1\*\* TODO is older than \*\*90 days\*\*/);
    assert.match(gh.comments[0]!.body, /in \[this run\]\(https:\/\/github\.com\/acme\/app\/actions\/runs\/42\)/);
    assert.ok(logs.some((l) => l.startsWith("Commented on pull request #7")));

    // A second run updates the same comment, even once nothing is stale.
    await run({ ...env, INPUT_DAYS: "5000" }, { log: () => {}, now: NOW, fetch: gh.fetch });
    assert.equal(gh.comments.length, 1);
    assert.match(gh.comments[0]!.body, /No TODOs older than \*\*5000 days\*\*/);
    assert.deepEqual(gh.requests.slice(-2), ["GET /repos/acme/app/issues/7/comments", "PATCH /repos/acme/app/issues/comments/100"]);
  });

  it("posts no comment while nothing is stale", async () => {
    const gh = fakeGitHub();
    await run({ ...baseEnv(), INPUT_COMMENT: "true", INPUT_DAYS: "5000" }, { log: () => {}, now: NOW, fetch: gh.fetch });
    assert.equal(gh.comments.length, 0);
    assert.deepEqual(gh.requests, ["GET /repos/acme/app/issues/7/comments"]);
  });

  it("skips the comment outside pull requests", async () => {
    const gh = fakeGitHub();
    const logs: string[] = [];
    const { GITHUB_EVENT_PATH: _, ...env } = baseEnv();
    await run({ ...env, INPUT_COMMENT: "true" }, { log: (l) => logs.push(l), now: NOW, fetch: gh.fetch });
    assert.equal(gh.requests.length, 0);
    assert.ok(logs.some((l) => l.startsWith("::notice title=stale-todo::comment works on pull_request events")));
  });

  it("creates, updates and closes the tracking issue", async () => {
    const gh = fakeGitHub();
    const outFile = join(repo, "..", `out-gh-${Date.now()}.txt`);
    writeFileSync(outFile, "");
    const env = { ...baseEnv(), GITHUB_OUTPUT: outFile, INPUT_ISSUE: "true", "INPUT_ISSUE-LABELS": "tech-debt, todo" };
    await run(env, { log: () => {}, now: NOW, fetch: gh.fetch });
    const created = gh.issues[2]!;
    assert.equal(created.title, "Stale TODOs");
    assert.deepEqual(created.labels, ["tech-debt", "todo"]);
    assert.ok(created.body.startsWith(ISSUE_MARKER));
    assert.match(readFileSync(outFile, "utf8"), /^issue-number<<ghadelimiter_[\w-]+\n3\n/m);

    await run({ ...env, "INPUT_ISSUE-TITLE": "Old TODOs" }, { log: () => {}, now: NOW, fetch: gh.fetch });
    assert.equal(gh.issues.length, 3);
    assert.equal(created.title, "Old TODOs");

    const logs: string[] = [];
    await run({ ...env, INPUT_DAYS: "5000" }, { log: (l) => logs.push(l), now: NOW, fetch: gh.fetch });
    assert.equal(created.state, "closed");
    assert.match(created.body, /No TODOs older than/);
    assert.ok(logs.some((l) => l === "Closed issue #3: u/3"));
    rmSync(outFile);
  });

  it("does not open an issue while nothing is stale", async () => {
    const gh = fakeGitHub();
    await run({ ...baseEnv(), INPUT_ISSUE: "true", INPUT_DAYS: "5000" }, { log: () => {}, now: NOW, fetch: gh.fetch });
    assert.equal(gh.issues.length, 2);
  });

  it("warns instead of failing when the token cannot post", async () => {
    const gh = fakeGitHub({ status: 403 });
    const logs: string[] = [];
    const code = await run({ ...baseEnv(), INPUT_COMMENT: "true", INPUT_ISSUE: "true" }, { log: (l) => logs.push(l), now: NOW, fetch: gh.fetch });
    assert.equal(code, 0);
    assert.ok(
      logs.some((l) =>
        l.startsWith(
          "::warning title=stale-todo::Could not comment on pull request #7. Give the job `permissions: pull-requests: write`. (GitHub API GET /repos/acme/app/issues/7/comments?per_page=100&page=1 returned 403",
        ),
      ),
      logs.join("\n"),
    );
    assert.ok(logs.some((l) => l.startsWith("::warning title=stale-todo::Could not update the tracking issue.")));
  });

  it("warns when there is no token", async () => {
    const logs: string[] = [];
    const { INPUT_TOKEN: _, ...env } = baseEnv();
    await run({ ...env, INPUT_ISSUE: "true", GITHUB_TOKEN: "" }, { log: (l) => logs.push(l), now: NOW, fetch: fakeGitHub().fetch });
    assert.ok(logs.some((l) => l.includes("needs the `token` input")));
  });
});
